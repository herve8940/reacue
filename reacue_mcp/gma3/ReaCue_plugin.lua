local function L() return TXT[(DATA and DATA.lang) == "en" and "en" or "fr"] end

local function log(s)
  if not pcall(Printf, "ReaCue: " .. tostring(s)) then pcall(Echo, "ReaCue: " .. tostring(s)) end
end

local function cmd(s)
  local ok, r = pcall(Cmd, s)
  return ok, r
end

local function q(s) return '"' .. tostring(s):gsub('"', "") .. '"' end

-- objets du show -------------------------------------------------------------------------------
local function pool(kind)
  local ok, dp = pcall(DataPool)
  if not ok or not dp then return nil end
  local ok2, p = pcall(function() return dp[kind] end)
  return ok2 and p or nil
end

local function child(p, i)
  local ok, o = pcall(function() return p[i] end)
  return ok and o or nil
end

local function obj_name(o)
  local ok, n = pcall(function() return o.name end)
  if ok and n ~= nil then return tostring(n) end
  ok, n = pcall(function() return o.Name end)
  return ok and n ~= nil and tostring(n) or nil
end

local MAX_NO = 9999

-- n° de l'objet de ce nom dans le pool, ou nil
local function find_by_name(kind, name)
  local p = pool(kind)
  if not p then return nil end
  for i = 1, MAX_NO do
    local o = child(p, i)
    if o and obj_name(o) == name then return i, o end
  end
  return nil
end

-- premier n° libre à partir de `from`
local function free_no(kind, from)
  local p = pool(kind)
  if not p then return from end
  for i = from or 1, MAX_NO do
    if not child(p, i) then return i end
  end
  return nil
end

local function exists(kind, no) local p = pool(kind); return p ~= nil and child(p, no) ~= nil end

-- lecteurs : clés USB d'abord, puis les autres (dont le disque interne)
local function drives()
  local list, rest = {}, {}
  local ok, dc = pcall(function() return Root().Temp.DriveCollect end)
  local n = 0
  if ok and dc then
    local okc, c = pcall(function() return dc.count end)
    if not okc or not c then okc, c = pcall(function() return dc:Count() end) end
    n = (okc and tonumber(c)) or 0
    for i = 1, n do
      local d = child(dc, i)
      local okt, ty = pcall(function() return d.DriveType end)
      if okt and tostring(ty):lower():find("remov") then list[#list + 1] = i else rest[#rest + 1] = i end
    end
  end
  if n == 0 then rest = { 1, 2, 3, 4 } end
  for _, i in ipairs(rest) do list[#list + 1] = i end
  return list
end

-- import d'un fichier de la bibliothèque (gma3_library/datapools/<kind>) au n° donné ; essaie
-- les syntaxes connues et vérifie que l'objet existe ensuite
local function import(kw, kind, file, no)
  local tries = {
    string.format("Import %s Library %s At %s %d", kw, q(file), kw, no),
    string.format("Import %s %d Library %s", kw, no, q(file)),
    string.format("Import %s %d %s", kw, no, q(file)),
  }
  for _, c in ipairs(tries) do
    cmd(c)
    if exists(kind, no) then return true end
  end
  return false
end

local function ask_replace(name, no)
  local t = L()
  local ok, r = pcall(MessageBox, {
    title = t.title, message = string.format(t.tc_replace_q, name, no),
    commands = { { value = 1, name = t.yes }, { value = 0, name = t.no } },
  })
  return ok and type(r) == "table" and r.result == 1
end

local function set_prop(no, prop, value)
  return cmd(string.format('Set Timecode %d Property %s %s', no, q(prop), q(value)))
end

local function read_prop(o, prop)
  local ok, v = pcall(function() return o[prop] end)
  return ok and v ~= nil and tostring(v) or nil
end

-- TC Slot : "Internal" (-2), "Link Selected" (-1), "Slot1" (0), "Slot2" (1)… (aide grandMA3, Timecode Keyword)
local function set_slot(no, slot)
  local p = pool("Timecodes")
  local o = p and child(p, no)
  if not o then return false end
  local function good()
    local v = read_prop(o, "TCSlot")
    if v == nil then return false end
    local s = v:lower():gsub("%s", "")
    return v == tostring(slot - 1) or s == "slot" .. slot or s == "tcslot" .. slot
  end
  set_prop(no, "TCSlot", "Slot" .. slot)
  if not good() then cmd(string.format('Set Timecode %d Property "TCSlot" %d', no, slot - 1)) end
  if not good() then pcall(function() o.TCSlot = slot - 1 end) end
  local ok = good()
  set_prop(no, "AutoStart", "Yes")
  set_prop(no, "AutoStop", "Yes")
  return ok
end

local function Main(displayHandle, argument)
  local t = L()
  if type(DATA) ~= "table" then log(t.no_data); return end
  local report = {}
  local function add(s) report[#report + 1] = s; log(s) end
  local slot = tonumber(DATA.slot) or 1
  local used_drive = nil

  -- 1. Sequences (avant le Timecode : il les désigne par leur nom)
  local todo = {}
  for _, s in ipairs(DATA.sequences or {}) do
    local no = find_by_name("Sequences", s.name)
    if no then add(string.format(t.seq_kept, s.name, no)) else todo[#todo + 1] = s end
  end
  local drv = drives()
  local function on_drive(fn)
    if used_drive then cmd("Drive " .. used_drive); return fn() end
    for _, d in ipairs(drv) do
      cmd("Drive " .. d)
      if fn() then used_drive = d; return true end
    end
    return false
  end
  for _, s in ipairs(todo) do
    local no = free_no("Sequences", 1)
    if no and on_drive(function() return import("Sequence", "Sequences", s.file, no) end) then
      add(string.format(t.seq_ok, s.name, no))
    else
      add(string.format(t.seq_fail, s.name, s.file))
    end
  end

  -- 2. Timecode
  local tc = DATA.timecode or {}
  local tc_no = nil
  if tc.file then
    local old = find_by_name("Timecodes", tc.name)
    local no
    if old and ask_replace(tc.name, old) then
      cmd(string.format("Delete Timecode %d /NoConfirm", old))
      no = exists("Timecodes", old) and free_no("Timecodes", 1) or old
    else
      no = free_no("Timecodes", 1)
    end
    if no and on_drive(function() return import("Timecode", "Timecodes", tc.file, no) end) then
      tc_no = no
      set_prop(no, "Name", tc.name)
      if old and old ~= no then add(string.format(t.tc_kept, tc.name, old, no))
      else add(string.format(t.tc_ok, tc.name, no)) end
    else
      add(string.format(t.tc_fail, tc.name, tc.file))
    end
  end

  -- 3. TC Slot
  if tc_no then
    if set_slot(tc_no, slot) then add(string.format(t.slot_ok, slot)) else add(string.format(t.slot_fail, slot)) end
  end
  if used_drive then add(string.format(t.drive, used_drive)) end
  cmd("Drive 1")

  -- 4. message de fin
  for _, h in ipairs(t.how) do report[#report + 1] = string.format(h, slot) end
  report[#report + 1] = t.done
  local msg = table.concat(report, "\n")
  local ok = pcall(MessageBox, { title = t.title, message = msg, commands = { { value = 1, name = t.ok } } })
  if not ok then log(msg) end
end

return Main
